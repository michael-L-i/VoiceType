import AppKit
import Carbon.HIToolbox
import VoiceTypeKit

/// Inserts text into the focused app by writing to the pasteboard and
/// synthesizing ⌘V, then restoring the previous clipboard contents.
///
/// Paste is the most reliable cross-app insertion path (works in editors,
/// browsers, chat apps) and preserves Unicode. Synthesizing the keystroke
/// requires Accessibility consent.
struct PasteboardInjector: TextInjector {
    /// How long the dictated text stays on the clipboard before the user's own
    /// contents come back. The target app reads the pasteboard when it gets
    /// around to handling ⌘V, which a busy browser or Electron app can take a
    /// few hundred ms to do; restoring before then pastes the old clipboard.
    private static let restoreDelay: TimeInterval = 0.5

    /// nspasteboard.org markers that clipboard managers honor: the dictated
    /// text is a delivery mechanism, not something the user copied, so it
    /// shouldn't pile up in (or sync out through) their clipboard history.
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    func inject(_ text: String) async throws {
        guard !text.isEmpty else { return }
        guard AXIsProcessTrusted() else { throw InjectionError.notTrusted }

        try await MainActor.run {
            // Escape may cancel the dictation while this injection is queued.
            // Check on the main actor immediately before touching the clipboard.
            try Task.checkCancellation()
            let pasteboard = NSPasteboard.general
            // Snapshot existing contents so we can restore them.
            let saved = PasteboardSnapshot(pasteboard)

            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            item.setData(Data(), forType: Self.transientType)
            item.setData(Data(), forType: Self.autoGeneratedType)
            pasteboard.clearContents()
            pasteboard.writeObjects([item])
            let ours = pasteboard.changeCount

            Self.sendCommandV()

            // Restore the user's clipboard once the paste has landed — unless
            // something else has claimed it since (the user copied anew), in
            // which case theirs is newer than our snapshot and wins.
            DispatchQueue.main.asyncAfter(deadline: .now() + Self.restoreDelay) {
                guard pasteboard.changeCount == ours else { return }
                saved.restore(to: pasteboard)
            }
        }
    }

    /// Post a synthetic ⌘V to the focused application.
    private static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey = CGKeyCode(kVK_ANSI_V)

        guard let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false) else {
            return
        }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cgAnnotatedSessionEventTap)
        up.post(tap: .cgAnnotatedSessionEventTap)
    }
}

/// Every item on the pasteboard with every representation it offers, in
/// order — so restoring brings back an image, a file or rich text, not just
/// whatever plain string came with it.
private struct PasteboardSnapshot {
    private let items: [[(type: NSPasteboard.PasteboardType, data: Data)]]

    init(_ pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored = items.map { representations in
            let item = NSPasteboardItem()
            for (type, data) in representations { item.setData(data, forType: type) }
            return item
        }
        if !restored.isEmpty { pasteboard.writeObjects(restored) }
    }
}
